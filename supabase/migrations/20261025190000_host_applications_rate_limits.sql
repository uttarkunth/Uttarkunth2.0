-- Uttarkunth Stays: private host onboarding and server-only atomic rate limits.
-- Additive migration. Existing property and booking rows are not modified.

create table if not exists public.host_applications (
  id uuid primary key default gen_random_uuid(),
  contact_name text not null check (char_length(contact_name) between 2 and 120),
  email text not null check (char_length(email) <= 254),
  phone text not null check (char_length(phone) between 7 and 40),
  property_name text not null check (char_length(property_name) between 2 and 160),
  village text not null check (char_length(village) between 2 and 160),
  district text not null check (char_length(district) between 2 and 160),
  state text not null default 'Himachal Pradesh',
  property_type text not null default 'homestay'
    check (property_type in ('homestay','guesthouse','hotel','resort','villa','cottage','other')),
  room_count integer not null check (room_count between 1 and 500),
  description text,
  ownership_confirmed boolean not null default false check (ownership_confirmed = true),
  status text not null default 'pending'
    check (status in ('pending','under_review','approved','rejected')),
  review_notes text,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists host_applications_status_created_idx
  on public.host_applications (status, created_at desc);
create index if not exists host_applications_email_idx
  on public.host_applications (lower(email));

alter table public.host_applications enable row level security;
revoke all on public.host_applications from public, anon, authenticated;
grant select, insert, update, delete on public.host_applications to service_role;

create table if not exists public.booking_rate_limits (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);
create index if not exists booking_rate_limits_hash_created_idx
  on public.booking_rate_limits (ip_hash, created_at desc);
alter table public.booking_rate_limits enable row level security;
revoke all on public.booking_rate_limits from public, anon, authenticated;
grant select, insert, delete on public.booking_rate_limits to service_role;

create or replace function public.try_consume_booking_rate_limit(
  p_ip_hash text,
  p_max_requests integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
  v_now timestamptz := pg_catalog.clock_timestamp();
begin
  if p_ip_hash is null or p_ip_hash !~ '^[0-9a-f]{64}$'
     or p_max_requests < 1 or p_max_requests > 100
     or p_window_seconds < 60 or p_window_seconds > 86400 then
    raise exception 'Invalid rate-limit input.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_ip_hash, 0));

  delete from public.booking_rate_limits
  where ip_hash = p_ip_hash
    and created_at < v_now - pg_catalog.make_interval(secs => p_window_seconds);

  select count(*)::integer into v_count
  from public.booking_rate_limits
  where ip_hash = p_ip_hash
    and created_at >= v_now - pg_catalog.make_interval(secs => p_window_seconds);

  if v_count >= p_max_requests then
    return false;
  end if;

  insert into public.booking_rate_limits (ip_hash, created_at) values (p_ip_hash, v_now);
  return true;
end;
$$;

revoke all on function public.try_consume_booking_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.try_consume_booking_rate_limit(text, integer, integer) to service_role;
